"""Render a standalone literature review from pipeline artifacts.

A literature-only run is Stages 1–7: topic scoping → queries → collection →
screening → knowledge cards → synthesis. This module turns those artifacts into
one markdown document, so the output is readable without walking `artifacts/`.

Used by ``researchclaw review``; works on any run directory that has at least a
collection or a shortlist, and degrades section by section when a later stage
did not run.
"""

from __future__ import annotations

import json
import logging
from datetime import datetime, timezone
from pathlib import Path
from typing import Any

logger = logging.getLogger(__name__)


# ---------------------------------------------------------------------------
# Artifact readers
# ---------------------------------------------------------------------------


def _read_text(path: Path | None) -> str:
    if path is None or not path.is_file():
        return ""
    try:
        return path.read_text(encoding="utf-8", errors="replace")
    except OSError:
        return ""


def _read_json(path: Path | None) -> dict[str, Any] | None:
    text = _read_text(path)
    if not text:
        return None
    try:
        data = json.loads(text)
    except json.JSONDecodeError:
        return None
    return data if isinstance(data, dict) else None


def _read_jsonl(path: Path | None) -> list[dict[str, Any]]:
    text = _read_text(path)
    rows: list[dict[str, Any]] = []
    for line in text.splitlines():
        line = line.strip()
        if not line:
            continue
        try:
            row = json.loads(line)
        except json.JSONDecodeError:
            continue
        if isinstance(row, dict):
            rows.append(row)
    return rows


def _find(run_dir: Path, relative: str) -> Path | None:
    """Find an artifact either at the run root or inside the newest stage dir."""
    direct = run_dir / relative
    if direct.exists():
        return direct
    matches = sorted(run_dir.glob(f"stage-*/{relative}"))
    return matches[-1] if matches else None


# ---------------------------------------------------------------------------
# Formatting helpers
# ---------------------------------------------------------------------------


def _short(text: Any, limit: int) -> str:
    value = " ".join(str(text or "").split())
    if len(value) <= limit:
        return value
    return value[: limit - 1].rstrip() + "…"


def _cell(text: Any) -> str:
    """Escape a value for a markdown table cell.

    Backslash first: escaping the pipe first and the backslash afterwards turns
    ``\\|`` into ``\\\\|``, which markdown renders as a literal backslash plus a
    cell split — one cell becomes two.
    """
    return _short(text, 200).replace("\\", "\\\\").replace("|", "\\|")


def _md_section(text: str, heading: str) -> str:
    """Return the body of the first ``## <heading>`` section."""
    wanted = heading.strip().lower()
    collected: list[str] = []
    inside = False
    for line in text.splitlines():
        stripped = line.strip()
        if stripped.startswith("## "):
            if inside:
                break
            inside = stripped[3:].strip().lower() == wanted
            continue
        if stripped.startswith("# "):
            if inside:
                break
            continue
        if inside:
            collected.append(line)
    return "\n".join(collected).strip()


def _demote_headings(text: str, levels: int = 1) -> str:
    """Push markdown headings down by *levels*, keeping code fences intact."""
    out: list[str] = []
    in_fence = False
    for line in text.splitlines():
        if line.strip().startswith("```"):
            in_fence = not in_fence
        elif not in_fence and line.startswith("#"):
            line = "#" * levels + line
        out.append(line)
    return "\n".join(out)


def _topic_from_artifacts(run_dir: Path) -> str:
    goal = _read_text(_find(run_dir, "goal.md"))
    topic = _md_section(goal, "Topic").splitlines()
    if topic and topic[0].strip():
        return topic[0].strip()
    queries = _read_json(_find(run_dir, "queries.json")) or {}
    found = queries.get("queries") or []
    if isinstance(found, list) and found:
        return str(found[0])
    return "Literature review"


# ---------------------------------------------------------------------------
# Sections
# ---------------------------------------------------------------------------


def _header(topic: str, run_dir: Path, search_meta: dict[str, Any] | None) -> str:
    generated = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M UTC")
    year_filter = (search_meta or {}).get("year_filter") or {}
    policy = ""
    if isinstance(year_filter, dict) and year_filter.get("active"):
        policy = f" Year policy: {year_filter.get('hint', '')}."
    return (
        f"# Literature review: {topic}\n\n"
        f"*Generated by ResearchClaw on {generated} from `{run_dir.name}`.*"
        f"{policy}\n"
    )


def _warnings_section(
    run_dir: Path, search_meta: dict[str, Any] | None
) -> str:
    warnings: list[str] = []
    if search_meta is not None and search_meta.get("real_search") is False:
        warnings.append(
            "**Candidates were synthesized by the LLM.** Every literature API "
            "failed (``real_search: false`` in ``search_meta.json``), so titles, "
            "venues and citation counts below may be fabricated."
        )
    cards_dir = _find(run_dir, "cards")
    if cards_dir is not None and cards_dir.is_dir():
        card_count = len(list(cards_dir.glob("*.md")))
        if card_count > 24:
            warnings.append(
                f"Synthesis was prompted with the first 24 of {card_count} "
                "evidence cards (the card context is capped); all cards are "
                "rendered below."
            )
    if not warnings:
        return ""
    lines = ["## Warnings", ""]
    lines.extend(f"- {warning}" for warning in warnings)
    return "\n".join(lines) + "\n"


def _scope_section(run_dir: Path) -> str:
    goal = _read_text(_find(run_dir, "goal.md")).strip()
    if not goal:
        return ""
    scope = _md_section(goal, "Scope") or _md_section(goal, "SMART Goal")
    if not scope:
        return ""
    return f"## Scope\n\n{_short(scope, 1200)}\n"


def _search_section(
    run_dir: Path, search_meta: dict[str, Any] | None
) -> str:
    queries_doc = _read_json(_find(run_dir, "queries.json")) or {}
    queries = queries_doc.get("queries") or []
    sources_doc = _read_json(_find(run_dir, "sources.json")) or {}
    sources = sources_doc.get("sources") or []

    meta = search_meta or {}
    hybrid = meta.get("hybrid_search") or {}
    lines = ["## Search strategy", ""]
    if isinstance(sources, list) and sources:
        names = [
            str(src.get("name") or src.get("id") or src)
            if isinstance(src, dict)
            else str(src)
            for src in sources
        ]
        lines.append(f"- **Sources:** {', '.join(names)}")
    if isinstance(queries, list) and queries:
        lines.append(f"- **Queries:** {len(queries)}")
    if meta.get("year_min") is not None:
        lines.append(f"- **Publication-year floor:** {meta.get('year_min')}")
    if isinstance(hybrid, dict) and hybrid.get("enabled"):
        lines.append(
            "- **Hybrid pass:** on — adds older foundations "
            f"({hybrid.get('foundational_added', 0)} papers added, "
            f"cap {hybrid.get('foundational_max_papers', 0)})"
        )
    lines.append("")
    if isinstance(queries, list) and queries:
        lines.append("| # | Query |")
        lines.append("|---|---|")
        for idx, query in enumerate(queries, 1):
            lines.append(f"| {idx} | {_cell(query)} |")
        lines.append("")
    return "\n".join(lines)


def _screening_section(
    candidates: list[dict[str, Any]],
    shortlist: list[dict[str, Any]],
    screen_meta: dict[str, Any] | None,
    search_meta: dict[str, Any] | None,
) -> str:
    meta = screen_meta or {}
    total = len(candidates) or int((search_meta or {}).get("total_candidates") or 0)
    lines = ["## Screening", ""]
    lines.append(f"- **Collected candidates:** {total}")
    screened = meta.get("candidates_screened")
    if screened is None:
        screened = meta.get("candidates_prefiltered")
    if screened is not None:
        lines.append(f"- **Passed keyword prefilter:** {screened}")
    if not shortlist and str(meta.get("outcome")) == "model_rejected_all":
        lines.append("- **Shortlist:** empty — the screener rejected every candidate")
        return "\n".join(lines) + "\n"
    lines.append(f"- **Shortlisted:** {len(shortlist)}")
    lines.append("")

    if shortlist:
        lines.append(
            "| # | Title | Year | Venue | Type | Cites | Relevance | Source |"
        )
        lines.append("|---|---|---|---|---|---|---|---|")
        for idx, row in enumerate(shortlist, 1):
            lines.append(
                "| {idx} | {title} | {year} | {venue} | {kind} | {cites} | {rel} | {src} |".format(
                    idx=idx,
                    title=_row_title(row),
                    year=_cell(row.get("year", "")),
                    venue=_cell(row.get("venue", "")),
                    kind=_cell(_paper_kind(row)),
                    cites=_cell(row.get("citation_count", "")),
                    rel=_cell(row.get("relevance_score", "")),
                    src=_cell(row.get("source", "")),
                )
            )
        lines.append("")
    return "\n".join(lines)


def _paper_kind(row: dict[str, Any]) -> str:
    """Evidence type for the review table: preprint, RCT, review …

    A biomedical review is read by someone who needs to see at a glance that a
    claim rests on a medRxiv preprint rather than a randomized trial. Every
    backend that can tell us already puts it in the row; this just surfaces it.
    """
    if row.get("is_preprint"):
        return "preprint"
    pub_types = row.get("pub_types") or []
    # A model that echoes the field sometimes flattens the list to one string;
    # the isinstance check below then fell through and blanked the Type column.
    if isinstance(pub_types, str):
        pub_types = [pub_types]
    if isinstance(pub_types, (list, tuple)):
        # MEDLINE lists the most specific type first ("Randomized Controlled
        # Trial" before "Journal Article"); prefer the first non-generic one.
        for value in pub_types:
            text = str(value).strip()
            if text and text.lower() not in {"journal article", "research support"}:
                return text
    return ""


def _row_title(row: dict[str, Any]) -> str:
    """Title cell with retraction/concern markers."""
    title = _cell(row.get("title", ""))
    marks = []
    if row.get("retracted"):
        marks.append("retracted")
    if row.get("concern"):
        marks.append("expression of concern")
    return f"{title} ⚠️ ({', '.join(marks)})" if marks else title


def _cards_section(run_dir: Path) -> str:
    cards_dir = _find(run_dir, "cards")
    if cards_dir is None or not cards_dir.is_dir():
        return ""
    card_files = sorted(cards_dir.glob("*.md"))
    if not card_files:
        return ""
    lines = ["## Evidence cards", ""]
    for path in card_files:
        body = _read_text(path).strip()
        if not body:
            continue
        # Cards carry their own H1/H2 headings; nest them under this section.
        lines.append(_demote_headings(body, levels=2))
        lines.append("")
    return "\n".join(lines)


def _synthesis_section(run_dir: Path) -> str:
    synthesis = _read_text(_find(run_dir, "synthesis.md")).strip()
    if not synthesis:
        return ""
    return f"## Synthesis and gaps\n\n{_demote_headings(synthesis)}\n"


def _references_section(shortlist: list[dict[str, Any]]) -> str:
    if not shortlist:
        return ""
    lines = ["## References", ""]
    for idx, row in enumerate(shortlist, 1):
        title = _short(row.get("title", "Untitled"), 200)
        year = row.get("year", "")
        venue = _short(row.get("venue", ""), 120)
        link = row.get("url") or row.get("doi") or ""
        suffix = f" <{link}>" if link else ""
        venue_part = f" *{venue}*." if venue else ""
        # A reference list is where a reader checks the source; a retracted
        # paper cited without a note is the one error a reviewer cannot see.
        flags = []
        if row.get("retracted"):
            flags.append("RETRACTED")
        if row.get("concern"):
            flags.append("expression of concern")
        if row.get("is_preprint"):
            flags.append("preprint")
        note = f" [{'; '.join(flags)}]" if flags else ""
        lines.append(f"{idx}. {title}.{venue_part} {year}.{suffix}{note}".rstrip())
    lines.append("")
    return "\n".join(lines)


# ---------------------------------------------------------------------------
# Public API
# ---------------------------------------------------------------------------


def generate_literature_review(run_dir: Path, *, topic: str = "") -> str:
    """Render a markdown literature review from *run_dir*.

    Never raises for missing artifacts: sections are skipped when their input
    does not exist, so a partially finished run still yields a usable document.
    """
    run_dir = Path(run_dir)
    candidates = _read_jsonl(_find(run_dir, "candidates.jsonl"))
    shortlist = _read_jsonl(_find(run_dir, "shortlist.jsonl"))
    search_meta = _read_json(_find(run_dir, "search_meta.json"))
    screen_meta = _read_json(_find(run_dir, "screen_meta.json"))

    resolved_topic = topic.strip() or _topic_from_artifacts(run_dir)

    sections = [
        _header(resolved_topic, run_dir, search_meta),
        _warnings_section(run_dir, search_meta),
        _scope_section(run_dir),
        _search_section(run_dir, search_meta),
        _screening_section(candidates, shortlist, screen_meta, search_meta),
        _cards_section(run_dir),
        _synthesis_section(run_dir),
        _references_section(shortlist),
    ]
    return "\n".join(section for section in sections if section).rstrip() + "\n"


def write_literature_review(
    run_dir: Path, *, topic: str = "", output: Path | None = None
) -> Path:
    """Render the review and write it to ``<run_dir>/review.md`` by default."""
    target = Path(output) if output is not None else Path(run_dir) / "review.md"
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(
        generate_literature_review(run_dir, topic=topic), encoding="utf-8"
    )
    return target
